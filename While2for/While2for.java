import java.util.Scanner;
public class While2for{
	public static void main(String [] args){
	
	
	int n = 0;
	
	while(n <= 10){
		System.out.print(n +" ");
		n++;
	}
	
	System.out.println(" ");
	
	for(int i=10;i>=0;i--){
		System.out.print(i+" ");
	}
	
	System.out.println(" ");
	
	for(int i=0;i<=10;i++){
		System.out.print(i+" ");
	}
	
	scanner.close();
	}	
}